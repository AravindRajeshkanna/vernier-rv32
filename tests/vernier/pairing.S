#*****************************************************************************
# pairing.S
#-----------------------------------------------------------------------------
#
# A co-simulation workload that actually dual-issues.
#
# The riscv-tests suites co-simulate against Spike instruction for
# instruction, and on the wide core they all match. They also retire 63
# instructions in slot 1 out of 28,262 - 0.22% - and 70 of the 82 traces
# retire none at all. So "82/82 match" is a statement about the wide core
# executing riscv-tests correctly, and almost nothing about the one mechanism
# that makes it a different core from cpu_core.v.
#
# This test exists to be the workload that is. It is not trying to catch a
# known bug; it is trying to make the strongest instrument in the project
# actually point at dual issue, so that a defect there has somewhere to show
# up. tests/cosim.py enforces a floor on how much of it pairs (MIN_SLOT1), so
# a change to the issue rule that quietly stops forming pairs fails here
# rather than passing a test that no longer tests anything.
#
# ---- how it pairs -------------------------------------------------------
#
# rtl/ooo/core_ooo.v forms a pair only when both halves are single-cycle
# integer ALU ops (OP-not-MUL/DIV, OP-IMM, LUI, AUIPC), slot 1 does not read
# what slot 0 writes, and slot 0's fetch was not predicted taken. It also
# needs two instructions *present*, and fetch delivers one per cycle - so in
# straight-line code the buffer runs dry and the machine issues singly no
# matter how independent the code is. Pairs come from backlog.
#
# Each iteration therefore opens with a divide. It is a 33-cycle occupancy of
# EX, which is long enough to fill the 4-deep fetch buffer, and the run of
# independent ALU ops behind it drains that buffer two at a time. The
# quotient is deliberately uninteresting - the instruction is here for its
# cycles, not its result - but it is folded into the accumulator anyway so
# the self-check covers it too.
#
# Measured, over ITERS = 2048 iterations: 6,143 retirements in slot 1 out of
# 30,804, or three pairs per iteration. Which three is not claimed here -
# the trace records program order, not which slot each instruction came out
# of, and the aggregate is what the floor is set against.
#
# ---- the expected value -------------------------------------------------
#
# The accumulator is checked against a constant, the same way every
# riscv-tests case checks against one. It is:
#
#   acc = sum over i in [0, ITERS) of
#           (i + 0x111) + (i ^ 0x222) + (i | 0x333) + (i & 0x444) + 1
#
# taken mod 2**32, where the trailing 1 is the quotient (i + K) / K for
# K = KDIV and i < K. tests/vernier/expected.py computes it into expected.h
# at build time, so what this test compares against is a derivation and not a
# copy of what some core once printed.
#

#include "riscv_test.h"
#include "test_macros.h"
# ITERS, KDIV and EXPECTED_ACC all come from here, and it is generated by
# tests/vernier/expected.py at build time. Nothing in this file may hardcode
# the answer.
#include "expected.h"

RVTEST_RV32U
RVTEST_CODE_BEGIN

  # TESTNUM has to be non-zero for TEST_PASSFAIL to reach `pass`, and it is
  # what a failure reports. One case, so one number.
  li      TESTNUM, 2

  li      s0, 0                   # i
  li      s1, ITERS
  li      s2, 0                   # accumulator

pair_loop:
  # ---- the stall that creates the backlog ----
  # `li` of a constant this size assembles to lui+addi - two in-class ops
  # that are themselves eligible to pair, which is why the constant is
  # rematerialized every iteration instead of being hoisted out of the loop.
  li      t4, KDIV
  add     t5, s0, t4
  divu    t6, t5, t4              # 33 cycles in EX; the buffer fills behind it

  # ---- the run that drains it two at a time ----
  # No two of these four share a register, so none of them is blocked by
  # `pair_raw`, and all four are in slot 1's class.
  addi    t0, s0, 0x111
  xori    t1, s0, 0x222
  ori     t2, s0, 0x333
  andi    t3, s0, 0x444

  # ---- fold ----
  # A dependent chain on purpose: it cannot pair, and it is here so the
  # accumulator's value depends on every result above. If dual issue writes
  # the wrong value into any of t0..t3, or writes them in the wrong order,
  # this is what carries it to the verdict.
  add     s2, s2, t0
  add     s2, s2, t1
  add     s2, s2, t2
  add     s2, s2, t3
  add     s2, s2, t6

  addi    s0, s0, 1
  bltu    s0, s1, pair_loop

  # ---- verdict ----
  li      t0, EXPECTED_ACC
  bne     s2, t0, fail

  TEST_PASSFAIL

RVTEST_CODE_END

  .data
RVTEST_DATA_BEGIN

  TEST_DATA

RVTEST_DATA_END
